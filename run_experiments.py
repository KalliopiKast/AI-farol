"""
run_experiments.py
Monte Carlo experiment runner: for each {agent_type} x {bar_type}
combination, runs N_SEEDS independent simulations at each of several
round counts, and reports both the raw per-seed values AND mean +/-
standard deviation across seeds for every tracked quantity (attendance,
price, profit, social welfare).

CHANGES vs. the version reviewed for the original submission:
  - Raw per-seed rows are now saved (results/raw_all_rounds.csv), not
    just the aggregated mean/std. Several cells were flagged in the paper
    as highly dispersed / possibly non-normal (e.g. no-regret x
    regression), so downstream statistical work (confidence intervals,
    Welch t-tests) should be computed from the raw per-seed samples --
    ideally via bootstrap for flagged cells -- rather than reconstructed
    from summary statistics alone. See analyze_results.py.
  - N_SEEDS default raised from 10 (as reported in the submitted paper)
    to N_SEEDS_DEFAULT below, now that the GP bar's runtime bug (see
    bar.py GPBar docstring) no longer makes a larger seed count
    impractical. This is a pragmatic compute-budget choice, not a
    methodologically derived minimum; see the paper's response-to-
    reviewers letter for the justification actually used.
  - Regret analysis (Section 5.6 of the paper) is now generated by this
    script via metrics.multi_seed_population_regret, rather than by
    whatever ad hoc / notebook process produced the original Figure 7 --
    that process is not in this repository's history, so it could not be
    reused directly; it is replaced here with a documented, rerunnable
    equivalent that also fixes the counterfactual bug described in
    metrics.py and averages over the whole no-regret population and
    multiple seeds instead of a single agent from a single run.
"""

import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from model import GameConfig
from simulation import run_simulation
from metrics import welfare_series, multi_seed_population_regret, convergence_round
from bar import _HAS_GP

OUT_DIR = "results"
os.makedirs(OUT_DIR, exist_ok=True)

AGENT_TYPES = ["heuristic", "bayesian", "no_regret", "q_learning"]
BAR_TYPES = ["passive", "regression", "q_learning"] + (["gp"] if _HAS_GP else [])
ROUND_COUNTS = [10, 100, 1000]

# Seed count: override via the AIFAROL_N_SEEDS environment variable, e.g.
#   AIFAROL_N_SEEDS=50 python run_experiments.py
# so the seed count used for a given run is explicit and reproducible
# without editing this file.
N_SEEDS_DEFAULT = 100
N_SEEDS = int(os.environ.get("AIFAROL_N_SEEDS", N_SEEDS_DEFAULT))


def _run_one_seed(agent_type, bar_type, rounds, seed):
    """Run a single simulation and return per-round-averaged summary stats
    for this one seed (attendance, price, profit, welfare), PLUS two
    diagnostics computed from the same round-by-round series at no extra
    simulation cost:
      - convergence_round_attendance (R3.4): the pre-registered
        trailing-window convergence diagnostic applied to this seed's
        attendance trajectory (None if the series never satisfies it, or
        is too short for the diagnostic's minimum window*(sustain+1)
        requirement -- always None at rounds=10 or 100 with the default
        window=200).
      - trailing_mean_attendance: mean attendance over the LAST 20% of
        rounds, as a companion to the whole-run mean. The whole-run mean
        can be a genuinely misleading summary for a pairing that
        collapses (or takes off) early and then holds steady: e.g.
        no_regret x passive was found this revision to hit an exact,
        permanent zero within the first ~50 rounds of a 1000-round run,
        after which it never moves again, yet the whole-run mean (~0.10)
        reads as "a small residual attendance level" rather than "fully
        collapsed almost immediately." The trailing mean reports where
        the process actually ends up; the whole-run mean is kept
        alongside it for continuity with the original submission's
        numbers, not replaced.
    """
    cfg = GameConfig(rounds=rounds, seed=seed)
    df, agents, bar = run_simulation(agent_type, bar_type, cfg=cfg, seed=seed)
    _, _, welfare = welfare_series(df["attendance"], df["price"], cfg)
    K = df["attendance"].values
    tail_start = max(0, int(len(K) * 0.8))
    return {
        "attendance": df["attendance"].mean(),
        "price": df["price"].mean(),
        "profit": df["profit"].mean(),
        "welfare": welfare.mean(),
        "distress_pct": bar.distress_periods / rounds * 100,
        "trailing_mean_attendance": float(np.mean(K[tail_start:])),
        "convergence_round_attendance": convergence_round(K),
    }


def monte_carlo_raw(agent_type, bar_type, rounds, n_seeds=N_SEEDS):
    """Run n_seeds independent simulations and return the RAW per-seed
    rows (one dict per seed), not yet aggregated."""
    rows = []
    for seed in range(n_seeds):
        stats = _run_one_seed(agent_type, bar_type, rounds, seed)
        stats.update({"agent_type": agent_type, "bar_type": bar_type,
                       "rounds": rounds, "seed": seed})
        rows.append(stats)
    return rows


def run_grid(round_counts=ROUND_COUNTS, n_seeds=N_SEEDS):
    """Full sweep: every agent x bar combination, at every round count.
    Writes BOTH the raw per-seed CSV (results/raw_all_rounds.csv) and the
    aggregated mean/std summary CSV (results/summary_all_rounds.csv, plus
    one summary_{rounds}rounds.csv per horizon, for backward
    compatibility with the plotting code below). Returns
    (raw_df, summary_df).
    """
    raw_rows = []
    summary_rows = []
    for rounds in round_counts:
        print(f"\n=== rounds = {rounds} (Monte Carlo over {n_seeds} seeds) ===")
        round_summary_rows = []
        for agent_type in AGENT_TYPES:
            for bar_type in BAR_TYPES:
                per_seed = monte_carlo_raw(agent_type, bar_type, rounds, n_seeds)
                raw_rows.extend(per_seed)

                df = pd.DataFrame(per_seed)
                summary = {"agent_type": agent_type, "bar_type": bar_type, "rounds": rounds}
                for col in ["attendance", "price", "profit", "welfare", "distress_pct",
                            "trailing_mean_attendance"]:
                    summary[f"{col}_mean"] = df[col].mean()
                    summary[f"{col}_std"] = df[col].std()
                conv = df["convergence_round_attendance"]
                summary["fraction_converged_attendance"] = conv.notna().mean()
                summary["median_convergence_round_attendance"] = conv.median()
                summary_rows.append(summary)
                round_summary_rows.append(summary)
                print(f"  {agent_type:12s} {bar_type:12s} "
                      f"K={summary['attendance_mean']:6.2f}+/-{summary['attendance_std']:5.2f}  "
                      f"p={summary['price_mean']:6.2f}+/-{summary['price_std']:5.2f}  "
                      f"profit={summary['profit_mean']:7.2f}+/-{summary['profit_std']:6.2f}  "
                      f"welfare={summary['welfare_mean']:7.2f}+/-{summary['welfare_std']:6.2f}")
        pd.DataFrame(round_summary_rows).to_csv(
            os.path.join(OUT_DIR, f"summary_{rounds}rounds.csv"), index=False)

    raw_df = pd.DataFrame(raw_rows)
    raw_df.to_csv(os.path.join(OUT_DIR, "raw_all_rounds.csv"), index=False)
    summary_df = pd.DataFrame(summary_rows)
    summary_df.to_csv(os.path.join(OUT_DIR, "summary_all_rounds.csv"), index=False)
    return raw_df, summary_df


def run_regret_analysis(bar_types=None, rounds=300, n_seeds=10, window=50):
    """Corrected replacement for the paper's Section 5.6 / Figure 7:
    population- and multi-seed-averaged empirical regret for the
    no_regret agent type against every bar type, using the counterfactual
    correction described in metrics.empirical_regret. Uses a smaller
    n_seeds than the main grid by default since this is O(seeds x agents)
    extra empirical_regret evaluations on top of the simulations
    themselves; raise it if compute allows.
    """
    bar_types = bar_types or BAR_TYPES
    cfg_template = GameConfig(rounds=rounds)
    all_rows = []
    plt.figure(figsize=(7, 5))
    for bar_type in bar_types:
        print(f"Regret analysis: no_regret x {bar_type} "
              f"({n_seeds} seeds, {rounds} rounds)...")
        traj = multi_seed_population_regret(
            "no_regret", bar_type, cfg_template, seeds=list(range(n_seeds)), window=window)
        for end, mean_r, std_r in traj:
            all_rows.append({"bar_type": bar_type, "round": end,
                              "mean_regret": mean_r, "std_regret": std_r})
        ends = [r[0] for r in traj]
        means = [r[1] for r in traj]
        stds = [r[2] for r in traj]
        plt.errorbar(ends, means, yerr=stds, marker="o", capsize=3, label=bar_type)

    plt.axhline(0, color="black", linestyle="--", linewidth=1, label="zero regret")
    plt.xlabel("Round")
    plt.ylabel("Population-mean empirical regret")
    plt.title(f"Corrected empirical regret: no_regret agents, "
              f"{n_seeds} seeds x population, by bar type")
    plt.legend(fontsize=9)
    plt.tight_layout()
    plt.savefig(os.path.join(OUT_DIR, "regret_corrected_no_regret.png"), dpi=150)
    plt.close()

    regret_df = pd.DataFrame(all_rows)
    regret_df.to_csv(os.path.join(OUT_DIR, "regret_corrected_no_regret.csv"), index=False)
    return regret_df


def run_section_5_9_checks(n_seeds=8, rounds=300):
    """The three reduced-scale robustness checks promised in Section 5.9
    of the revised draft, each a controlled before/after comparison on
    the SAME corrected codebase (not a re-run of the original, unfixed
    implementation -- see bar.py/metrics.py docstrings for why that
    would confound several simultaneous changes). Matches the drafted
    spec of n_seeds=8, rounds=300. Writes one CSV per check to results/.
    """
    from metrics import regret_before_after
    import copy as copy_module

    # --- R3.1: partial observability, disabled (public feedback) vs
    # enabled (the corrected default) -- heuristic and bayesian agents
    # only, since their belief formation is the channel this affects.
    rows = []
    for agent_type in ["heuristic", "bayesian"]:
        for bar_type in BAR_TYPES:
            for use_public in [True, False]:
                for seed in range(n_seeds):
                    cfg = GameConfig(rounds=rounds, seed=seed)
                    df, agents, bar = run_simulation(
                        agent_type, bar_type, cfg=cfg, seed=seed,
                        agent_kwargs={"use_public_feedback": use_public})
                    rows.append({
                        "agent_type": agent_type, "bar_type": bar_type,
                        "condition": "public_feedback" if use_public else "corrected_subset_observability",
                        "seed": seed, "attendance_mean": df["attendance"].mean(),
                        "price_mean": df["price"].mean(), "profit_mean": df["profit"].mean(),
                    })
    pd.DataFrame(rows).to_csv(os.path.join(OUT_DIR, "r3_1_observability_check.csv"), index=False)
    print(f"R3.1 check written ({len(rows)} rows).")

    # --- R3.2: regret counterfactual, before vs after, on IDENTICAL
    # simulated data (no extra runs beyond generating that data once).
    rows = []
    for bar_type in BAR_TYPES:
        for seed in range(n_seeds):
            cfg = GameConfig(rounds=rounds, seed=seed)
            df, agents, bar = run_simulation("no_regret", bar_type, cfg=cfg, seed=seed)
            for agent in agents:
                r = regret_before_after(agent, df["attendance"].values, df["price"].values, cfg)
                r.update({"bar_type": bar_type, "seed": seed, "agent_id": agent.id})
                rows.append(r)
    pd.DataFrame(rows).to_csv(os.path.join(OUT_DIR, "r3_2_regret_before_after.csv"), index=False)
    print(f"R3.2 check written ({len(rows)} rows).")

    # --- R3.3: price-aware vs price-blind regression bar -- bayesian and
    # q_learning agents, since these are the price-sensitive decision
    # rules per the drafted text.
    rows = []
    for agent_type in ["bayesian", "q_learning"]:
        for use_price in [True, False]:
            for seed in range(n_seeds):
                cfg = GameConfig(rounds=rounds, seed=seed)
                df, agents, bar = run_simulation(
                    agent_type, "regression", cfg=cfg, seed=seed,
                    bar_kwargs={"use_price_feature": use_price})
                rows.append({
                    "agent_type": agent_type,
                    "condition": "price_aware" if use_price else "price_blind",
                    "seed": seed, "attendance_mean": df["attendance"].mean(),
                    "price_mean": df["price"].mean(), "profit_mean": df["profit"].mean(),
                })
    pd.DataFrame(rows).to_csv(os.path.join(OUT_DIR, "r3_3_price_feature_check.csv"), index=False)
    print(f"R3.3 check written ({len(rows)} rows).")


def plot_convergence(summary_df, agent_type, bar_type, metric="attendance"):
    """Plot how a given metric's mean +/- std evolves across round counts,
    for one agent x bar combination -- shows convergence behavior
    directly, which a single fixed round count cannot."""
    sub = summary_df[(summary_df.agent_type == agent_type) & (summary_df.bar_type == bar_type)]
    sub = sub.sort_values("rounds")
    plt.figure(figsize=(6, 4))
    plt.errorbar(sub["rounds"], sub[f"{metric}_mean"], yerr=sub[f"{metric}_std"],
                 marker="o", capsize=4)
    plt.xscale("log")
    plt.xlabel("Rounds (log scale)")
    plt.ylabel(metric)
    plt.title(f"{agent_type} + {bar_type}: {metric} vs. rounds")
    plt.tight_layout()
    fname = f"convergence_{agent_type}_{bar_type}_{metric}.png"
    plt.savefig(os.path.join(OUT_DIR, fname), dpi=150)
    plt.close()


def plot_combined_convergence(summary_df, combos, metric="attendance"):
    """Plot the same metric's convergence for SEVERAL combos on one chart,
    one line per combo, so they can be compared directly instead of
    flipping between separate single-combo plots."""
    plt.figure(figsize=(7, 5))
    for agent_type, bar_type in combos:
        sub = summary_df[(summary_df.agent_type == agent_type) & (summary_df.bar_type == bar_type)]
        sub = sub.sort_values("rounds")
        label = f"{agent_type} + {bar_type}"
        plt.errorbar(sub["rounds"], sub[f"{metric}_mean"], yerr=sub[f"{metric}_std"],
                     marker="o", capsize=4, label=label)
    plt.xscale("log")
    plt.xlabel("Rounds (log scale)")
    plt.ylabel(metric)
    plt.title(f"{metric} vs. rounds, across game combinations")
    plt.legend(fontsize=9)
    plt.tight_layout()
    fname = f"combined_convergence_{metric}.png"
    plt.savefig(os.path.join(OUT_DIR, fname), dpi=150)
    plt.close()


if __name__ == "__main__":
    raw_df, summary_df = run_grid()

    key_combos = [
        ("heuristic", "passive"),
        ("heuristic", "q_learning"),
        ("no_regret", "passive"),
        ("no_regret", "q_learning"),
    ]
    for agent_type, bar_type in key_combos:
        for metric in ["attendance", "price", "profit", "welfare"]:
            plot_convergence(summary_df, agent_type, bar_type, metric)
    for metric in ["attendance", "price", "profit", "welfare"]:
        plot_combined_convergence(summary_df, key_combos, metric)

    run_regret_analysis(rounds=300, n_seeds=10, window=50)
    run_section_5_9_checks(n_seeds=8, rounds=300)

    print(f"\nAll CSVs and plots saved to ./{OUT_DIR}/")
